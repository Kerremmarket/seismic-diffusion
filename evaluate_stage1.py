#!/usr/bin/env python3
"""Stage 1 diffusion evaluation script.

Computes quantitative metrics comparing real Z-component traces against
synthetic samples generated by the Stage 1 diffusion model.
"""

import argparse
import json
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np
import pandas as pd
import torch
import yaml

from model_stage1 import ConditionalUNet1D, UNet1DConfig
from train_stage1 import DiffusionConfig, DiffusionTrainer, ExponentialMovingAverage, load_checkpoint


DATA_ROOT = Path("/Users/keremciftci/Desktop/KO_ARMT_data")
DEFAULT_CHECKPOINT_DIR = Path("stage1_runs")


def read_checkpoint_config(checkpoint_path: Path) -> dict:
    cfg: dict = {}
    if checkpoint_path is None:
        return cfg
    candidate = checkpoint_path.parent / "config_used.yaml"
    if not candidate.exists():
        parent = checkpoint_path.parent.parent
        if parent != checkpoint_path.parent:
            alt = parent / "config_used.yaml"
            if alt.exists():
                candidate = alt
    if candidate.exists():
        cfg = json.loads(candidate.read_text()) if candidate.suffix == ".json" else yaml.safe_load(candidate.read_text())
        if cfg is None:
            cfg = {}
    return cfg


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Evaluate Stage 1 diffusion model.")
    parser.add_argument("--data-root", type=Path, default=DATA_ROOT)
    parser.add_argument("--artifact-version", type=str, default="v1", help="Dataset artifact version (v1, v2, ...)")
    parser.add_argument(
        "--checkpoint",
        type=Path,
        default=None,
        help="Path to checkpoint (.pt). If omitted, uses newest checkpoint in stage1_runs/.",
    )
    parser.add_argument("--output-dir", type=Path, default=Path("stage1_eval"))
    parser.add_argument("--val-fraction", type=float, default=0.2, help="Fraction of events reserved for validation.")
    parser.add_argument("--max-events", type=int, default=100, help="Number of validation events to evaluate (0 = all).")
    parser.add_argument("--samples-per-event", type=int, default=4, help="Synthetic samples per event.")
    parser.add_argument("--slice-len", type=int, default=4096, help="Number of samples per trace.")
    parser.add_argument("--sample-steps", type=int, default=100, help="Diffusion steps for sampling.")
    parser.add_argument("--device", type=str, default="cpu", help="Device for sampling (cpu/mps/cuda).")
    parser.add_argument("--timesteps", type=int, default=200, help="Number of diffusion timesteps used during training.")
    parser.add_argument("--beta-start", type=float, default=1e-4)
    parser.add_argument("--beta-end", type=float, default=0.02)
    return parser.parse_args()


def load_arrays(data_root: Path):
    traces = np.load(data_root / "z_traces.npy", mmap_mode="r")
    conditions = np.load(data_root / "z_conditions.npy")
    eq_codes_df = pd.read_csv(data_root / "z_eq_codes.csv", dtype={"eq_code": str})
    events_path = data_root / "processed_events.csv"
    if not events_path.exists():
        events_path = DATA_ROOT / "processed_events.csv"
    events_df = pd.read_csv(events_path, dtype={"eq_code": str})
    eq_codes = eq_codes_df["eq_code"].tolist()

    station_ids = None
    station_vocab: dict[str, int] = {}
    if "station" in events_df.columns:
        eq_to_station = dict(
            zip(events_df["eq_code"].astype(str), events_df["station"].astype(str))
        )
        ids: list[int] = []
        for code in eq_codes:
            station = eq_to_station.get(code)
            if station is None:
                ids.append(0)
                continue
            if station not in station_vocab:
                station_vocab[station] = len(station_vocab) + 1
            ids.append(station_vocab.get(station, 0))
        station_ids = np.asarray(ids, dtype=np.int64)
    return traces, conditions, eq_codes, events_df, station_ids, station_vocab


def select_checkpoint(provided: Path | None) -> Path:
    if provided is not None:
        if not provided.exists():
            raise FileNotFoundError(provided)
        return provided
    if not DEFAULT_CHECKPOINT_DIR.exists():
        raise FileNotFoundError("No checkpoint provided and stage1_runs/ not found.")
    candidates = list(DEFAULT_CHECKPOINT_DIR.glob("checkpoint_*.pt"))
    if not candidates:
        raise FileNotFoundError("No checkpoint files found in stage1_runs/.")
    candidates.sort(key=lambda p: p.stat().st_mtime, reverse=True)
    return candidates[0]


def build_eval_split(eq_codes: List[str], events_df: pd.DataFrame, val_fraction: float) -> pd.DataFrame:
    df = pd.DataFrame({"eq_code": eq_codes, "dataset_idx": np.arange(len(eq_codes))})
    df = df.merge(events_df, on="eq_code", how="left")
    df["time"] = pd.to_datetime(df["time"])
    df.sort_values("time", inplace=True)
    val_start = int(len(df) * (1.0 - val_fraction))
    val_start = max(val_start, 0)
    return df.iloc[val_start:].reset_index(drop=True)


def preprocess_trace(trace: np.ndarray, slice_len: int, standardize: bool = True) -> np.ndarray:
    x = trace[:slice_len].astype(np.float32).copy()
    if standardize:
        mean = float(x.mean())
        std = float(x.std())
        if std > 0:
            x = (x - mean) / std
        else:
            x = x * 0.0
    return x


def max_cross_correlation(a: np.ndarray, b: np.ndarray) -> Tuple[float, int]:
    corr = np.correlate(a, b, mode="full")
    denom = np.linalg.norm(a) * np.linalg.norm(b) + 1e-8
    corr /= denom
    lag = int(np.argmax(corr) - (len(a) - 1))
    return float(np.max(corr)), lag


def align_trace(reference: np.ndarray, candidate: np.ndarray, lag: int) -> np.ndarray:
    if lag == 0:
        return candidate
    if lag > 0:
        aligned = np.concatenate([np.zeros(lag, dtype=np.float32), candidate])[: len(reference)]
    else:
        aligned = candidate[-lag:]
        if aligned.size < reference.size:
            aligned = np.concatenate([aligned, np.zeros(reference.size - aligned.size, dtype=np.float32)])
    return aligned.astype(np.float32)


def compute_metrics(real: np.ndarray, synth: np.ndarray) -> Dict[str, float]:
    synth = synth[: real.shape[0]]
    mae = float(np.mean(np.abs(real - synth)))
    mse = float(np.mean((real - synth) ** 2))
    corr, lag = max_cross_correlation(real, synth)
    synth_aligned = align_trace(real, synth, lag)
    mae_aligned = float(np.mean(np.abs(real - synth_aligned)))
    mse_aligned = float(np.mean((real - synth_aligned) ** 2))

    # Spectral comparison
    real_fft = np.abs(np.fft.rfft(real))
    synth_fft = np.abs(np.fft.rfft(synth_aligned))
    spectral_l2 = float(np.mean((real_fft - synth_fft) ** 2))

    stats = {
        "mae": mae,
        "mse": mse,
        "mae_aligned": mae_aligned,
        "mse_aligned": mse_aligned,
        "max_corr": corr,
        "lag_samples": float(lag),
        "std_real": float(real.std()),
        "std_synth": float(synth.std()),
        "ptp_real": float(real.max() - real.min()),
        "ptp_synth": float(synth.max() - synth.min()),
        "spectral_l2": spectral_l2,
    }
    return stats


def aggregate_metrics(per_event: List[Dict[str, float]]) -> Dict[str, Dict[str, float]]:
    summary: Dict[str, Dict[str, float]] = {}
    if not per_event:
        return summary
    # Only aggregate numeric metric keys (skip identifiers like eq_code).
    keys = [key for key in per_event[0].keys() if key != "eq_code"]
    for key in keys:
        values = np.array([item[key] for item in per_event], dtype=np.float64)
        summary[key] = {
            "mean": float(np.mean(values)),
            "std": float(np.std(values)),
            "median": float(np.median(values)),
        }
    return summary


def main():
    args = parse_args()
    device = torch.device(args.device)
    if args.artifact_version == "v1":
        data_root = args.data_root
    else:
        data_root = args.data_root / "artifacts" / args.artifact_version
    output_dir = args.output_dir / args.artifact_version
    output_dir.mkdir(parents=True, exist_ok=True)

    traces, conditions, eq_codes, events_df, station_ids, station_vocab = load_arrays(data_root)
    val_df = build_eval_split(eq_codes, events_df, args.val_fraction)
    if args.max_events > 0:
        val_df = val_df.head(args.max_events)

    checkpoint_path = select_checkpoint(args.checkpoint)
    print(f"[eval] using checkpoint: {checkpoint_path}")

    ckpt_config = read_checkpoint_config(checkpoint_path)
    dataset_cfg = ckpt_config.get("dataset", {})
    model_cfg_dict = ckpt_config.get("model", {})
    diffusion_cfg_dict = ckpt_config.get("diffusion", {})
    loss_cfg = ckpt_config.get("loss", {})

    slice_len_eval = min(args.slice_len, traces.shape[1])
    window_cfg = dataset_cfg.get("window", {})
    if "slice_len_samples" in window_cfg:
        slice_len_eval = int(window_cfg["slice_len_samples"])

    base_channels = model_cfg_dict.get("base_channels", 64)
    channel_multipliers = tuple(model_cfg_dict.get("channel_multipliers", (1, 2, 4)))
    num_res_blocks = model_cfg_dict.get("num_res_blocks", 2)
    kernel_size = model_cfg_dict.get("kernel_size", 3)
    time_embedding_dim = model_cfg_dict.get("time_embedding_dim", 256)
    station_embedding_dim = model_cfg_dict.get("station_embedding_dim", 0)
    use_attention = model_cfg_dict.get("use_attention", True)
    attention_heads = model_cfg_dict.get("attention_heads", 4)
    mid_dilations = tuple(model_cfg_dict.get("mid_dilations", (1, 2, 4)))

    model_cfg = UNet1DConfig(
        in_channels=1,
        base_channels=base_channels,
        channel_multipliers=channel_multipliers,
        num_res_blocks=num_res_blocks,
        kernel_size=kernel_size,
        time_embedding_dim=time_embedding_dim,
        cond_dim=conditions.shape[1],
        station_embedding_dim=station_embedding_dim,
        num_stations=len(station_vocab) + 1 if station_vocab else 0,
        use_attention=use_attention,
        attention_heads=attention_heads,
        mid_dilations=mid_dilations,
    )
    model = ConditionalUNet1D(model_cfg)
    diffusion_cfg = DiffusionConfig(
        num_timesteps=diffusion_cfg_dict.get("timesteps", args.timesteps),
        beta_start=diffusion_cfg_dict.get("beta_start", args.beta_start),
        beta_end=diffusion_cfg_dict.get("beta_end", args.beta_end),
        schedule=diffusion_cfg_dict.get("schedule", "cosine"),
        target=diffusion_cfg_dict.get("target", "eps"),
        classifier_free_dropout=diffusion_cfg_dict.get("classifier_free_dropout", 0.0),
    )
    sample_rate = dataset_cfg.get("sample_rate", 100.0)
    trainer = DiffusionTrainer(model, diffusion_cfg, device, sample_rate=sample_rate, loss_cfg=loss_cfg)
    standardize_eval = dataset_cfg.get("norm_mode", "per_trace") != "global"

    ema = ExponentialMovingAverage(model.parameters(), decay=0.0)
    load_checkpoint(checkpoint_path, model, optimizer=None, ema=ema)
    ema.copy_to(model.parameters())
    model.eval()

    metrics_records: List[Dict[str, float]] = []
    per_event_details: List[Dict[str, float]] = []

    for _, row in val_df.iterrows():
        idx = int(row["dataset_idx"])
        eq_code = row["eq_code"]

        real_trace = preprocess_trace(traces[idx], slice_len_eval, standardize=standardize_eval)
        cond = torch.from_numpy(conditions[idx : idx + 1]).float().to(device)
        station_tensor = None
        if station_ids is not None:
            station_tensor = torch.from_numpy(station_ids[idx : idx + 1]).long().to(device)

        sample_metrics = defaultdict(list)
        for sample_idx in range(args.samples_per_event):
            samples = trainer.sample_traces(
                cond,
                slice_len=slice_len_eval,
                steps=args.sample_steps,
                sample_device=device,
                station_ids=station_tensor,
            )
            synth = samples.squeeze(0).squeeze(0).cpu().numpy()
            metrics = compute_metrics(real_trace, synth)
            for key, value in metrics.items():
                sample_metrics[key].append(value)

        averaged = {key: float(np.mean(values)) for key, values in sample_metrics.items()}
        averaged["eq_code"] = eq_code
        metrics_records.append(averaged)
        per_event_details.append(averaged)
        print(
            f"[event {eq_code}] "
            f"MAE={averaged['mae_aligned']:.4f} "
            f"MSE={averaged['mse_aligned']:.4f} "
            f"corr={averaged['max_corr']:.3f}"
        )

    metrics_df = pd.DataFrame(per_event_details)
    metrics_csv = output_dir / "metrics_per_event.csv"
    metrics_df.to_csv(metrics_csv, index=False)
    summary = aggregate_metrics(per_event_details)
    summary_path = output_dir / "metrics_summary.json"
    summary_path.write_text(json.dumps(summary, indent=2))

    print(f"[eval] wrote per-event metrics to {metrics_csv}")
    print(f"[eval] summary:\n{json.dumps(summary, indent=2)}")


if __name__ == "__main__":
    main()


